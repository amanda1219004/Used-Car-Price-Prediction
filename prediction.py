import streamlit as st
import pandas as pd
import joblib



model = joblib.load(
    'gradient_boosting_tuned.joblib'
)

selected_features = joblib.load(
    'selected_features.joblib'
)

def run():
    st.title("Input Your Car details in Here!")

#buat form
    with st.form(
        'car_prediction_form'
    ):
        name = st.text_input(
            'Car Name',
            value='Maruti Swift Dzire'
        )
        year = st.number_input(
            'Manufacturing Year',
            min_value=1990,
            max_value=2020,
            value=2018,
            step=1
        )
        km_driven = st.number_input(
            'Kilometers Driven',
            min_value=0,
            value=45000,
            step=1000
        )
        fuel = st.selectbox(
            'Fuel Type',
            (
                'Petrol',
                'Diesel',
                'CNG',
                'LPG'
            )
        )
        seller_type = st.selectbox(
            'Seller Type',
            (
                'Individual',
                'Dealer',
                'Trustmark Dealer'
            )
        )
        transmission = st.selectbox(
            'Transmission',
            (
                'Manual',
                'Automatic'
            )
        )
        owner = st.selectbox(
            'Owner',
            (
                'First Owner',
                'Second Owner',
                'Third Owner',
                'Fourth & Above Owner',
                'Test Drive Car'
            )
        )
        mileage = st.number_input(
            'Mileage (km/ltr/kg)',
            min_value=0.0,
            value=22.0,
            step=0.1
        )
        engine = st.number_input(
            'Engine Capacity (CC)',
            min_value=0.0,
            value=1248.0,
            step=1.0
        )
        max_power = st.number_input(
            'Maximum Power',
            min_value=0.0,
            value=74.0,
            step=1.0
        )
        seats = st.number_input(
            'Number of Seats',
            min_value=2,
            max_value=15,
            value=5,
            step=1
        )

        submit = st.form_submit_button(
            'Predict Selling Price'
        )

# buat data baru
    data_inf = pd.DataFrame({
        'name': [name],
        'year': [year],
        'km_driven': [km_driven],
        'fuel': [fuel],
        'seller_type': [seller_type],
        'transmission': [transmission],
        'owner': [owner],
        'mileage(km/ltr/kg)': [mileage],
        'engine': [engine],
        'max_power': [max_power],
        'seats': [seats]
    })

# prediction
    if submit:
        st.subheader('Input Data')

        st.dataframe(
            data_inf,
            use_container_width=True
        )

# lakukan feature eng
        REFERENCE_YEAR = 2020

        # Create vehicle age
        data_inf['car_age'] = (
            REFERENCE_YEAR
            - data_inf['year']
        )

        # Extract vehicle brand
        data_inf['brand'] = (
            data_inf['name']
            .str.split()
            .str[0]
        )

        # Remove original columns
        data_inf = data_inf.drop(
            columns=[
                'name',
                'year'
            ]
        )

# feature select
        data_inf_final = data_inf[
            selected_features
        ]

# predict price
        prediction = model.predict(
            data_inf_final
        )

# result
        predicted_price = prediction[0]

        st.success(
            f'Estimated Selling Price: '
            f'₹{predicted_price:,.2f}'
        )

        st.write(
            '''
            The estimated price is generated by the tuned
            Gradient Boosting Regression model based on the
            vehicle characteristics provided above.
            '''
        )

if __name__ == '__main__':
    run()
